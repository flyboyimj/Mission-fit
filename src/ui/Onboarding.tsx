import { useState } from 'react';
import { screeningComplete } from '../engine/health';
import { todayIso } from '../engine/plan';
import { useStore } from '../store/AppStore';
import type { Profile } from '../types';
import { Banner, Chips, SafetyContent, Toggle } from './kit';
import { ClearanceForm, LimitationsEditor, ScreeningForm, ScreeningResult } from './ProfileParts';

const STEPS = ['Welcome', 'Body', 'Limitations', 'Screening', 'Guidance', 'Equipment', 'Safety'];

export function Onboarding() {
  const { data, update, persistent } = useStore();
  const [i, setI] = useState(0);
  const [p, setP] = useState<Profile>(data.profile);
  const [ack, setAck] = useState(false);
  const [limitsTouched, setLimitsTouched] = useState(false);
  const patch = (x: Partial<Profile>) => setP((cur) => ({ ...cur, ...x }));

  const canNext = i === 3 ? screeningComplete(p.screening) : i === 6 ? ack : true;
  const finish = () => {
    const now = new Date().toISOString();
    update((d) => ({
      ...d,
      profile: { ...p, onboarded: true, limitationsConfirmedAt: now, screeningAt: p.screeningAt ?? now },
      body: p.currentWeight > 0
        ? [...d.body.filter((b) => b.date !== todayIso()), { ...d.body.find((b) => b.date === todayIso()), date: todayIso(), weight: p.currentWeight }]
        : d.body,
    }));
  };

  return (
    <div className="onboard">
      <div className="onboard-progress" aria-label={`Step ${i + 1} of ${STEPS.length}`}>
        {STEPS.map((s, idx) => <span key={s} className={idx <= i ? 'on' : ''} />)}
      </div>
      <p className="eyebrow">Step {i + 1} of {STEPS.length} · {STEPS[i]}</p>

      {i === 0 && (
        <div className="stack">
          <h1 className="brand">Mission Fit</h1>
          <p className="lede">Structured, military-inspired training built around your body, your equipment and your recovery.</p>
          <ul className="bullets">
            <li>Workouts are generated by transparent rules — no AI service, no account.</li>
            <li>Your answers and history stay in this browser. Nothing is transmitted.</li>
            <li>This app supports fitness habits. It is not medical advice.</li>
          </ul>
          {!persistent && <Banner tone="warn">Browser storage is unavailable here, so your data will not be saved after you close this page. Use Export in Profile to keep a copy.</Banner>}
        </div>
      )}

      {i === 1 && (
        <div className="stack">
          <h1>Confirm the basics</h1>
          <p className="muted">Pre-filled from what you shared. Edit anything that's changed.</p>
          <div className="grid2">
            <label className="field" htmlFor="ob-age"><span className="label">Age</span><input id="ob-age" inputMode="numeric" value={p.age || ''} onChange={(e) => patch({ age: parseInt(e.target.value) || 0 })} /></label>
            <label className="field" htmlFor="ob-name"><span className="label">Name (optional)</span><input id="ob-name" value={p.name} onChange={(e) => patch({ name: e.target.value })} /></label>
            <label className="field" htmlFor="ob-cw"><span className="label">Current weight (lb)</span><input id="ob-cw" inputMode="decimal" value={p.currentWeight || ''} onChange={(e) => patch({ currentWeight: parseFloat(e.target.value) || 0 })} /></label>
            <label className="field" htmlFor="ob-gw"><span className="label">Goal weight (lb)</span><input id="ob-gw" inputMode="decimal" value={p.goalWeight || ''} onChange={(e) => patch({ goalWeight: parseFloat(e.target.value) || 0 })} /></label>
          </div>
        </div>
      )}

      {i === 2 && (
        <div className="stack">
          <h1>Which limitations are active now?</h1>
          <p className="muted">You've told me about these before. Old issues sometimes resolve — mark each one as it is today. You can change this anytime.</p>
          <LimitationsEditor profile={p} onChange={(l) => { setLimitsTouched(true); patch({ limitations: l }); }} />
          {!limitsTouched && <p className="muted small">Nothing changed? That's fine — tap Next to confirm as shown.</p>}
        </div>
      )}

      {i === 3 && (
        <div className="stack">
          <h1>Health screening</h1>
          <p className="muted">Eight yes/no questions to decide whether clinician guidance is needed before vigorous exercise.</p>
          <ScreeningForm value={p.screening} onAnswer={(k, v) => setP((cur) => ({ ...cur, screening: { ...cur.screening, [k]: v }, screeningAt: new Date().toISOString() }))} />
          {screeningComplete(p.screening) && <ScreeningResult profile={p} />}
        </div>
      )}

      {i === 4 && (
        <div className="stack">
          <h1>Clinician guidance</h1>
          <ScreeningResult profile={p} />
          <ClearanceForm profile={p} onChange={(c) => patch({ clearance: c })} />
          <p className="muted small">Skip this if you haven't had the conversation yet — you can train at moderate effort and add it later in Profile.</p>
        </div>
      )}

      {i === 5 && (
        <div className="stack">
          <h1>Where do you usually train?</h1>
          <Chips id="ob-loc" value={p.defaultLocation} onChange={(v) => patch({ defaultLocation: v })} options={[{ value: 'gym', label: 'Commercial gym' }, { value: 'home', label: 'Home' }]} />
          <p className="muted">Default gym: dumbbells 5–100 lb, kettlebells, cables, nine common machines, bike, elliptical, treadmill and rower. Default home: dumbbells 10–50 lb, kettlebells and a bench. Fine-tune both in Profile, or per workout in Build.</p>
        </div>
      )}

      {i === 6 && (
        <div className="stack">
          <h1>Before your first mission</h1>
          <SafetyContent />
          <Toggle id="ob-ack" checked={ack} onChange={setAck} label="I'll stop and get help if I notice these" />
        </div>
      )}

      <div className="onboard-nav">
        {i > 0 && <button type="button" className="btn ghost" onClick={() => setI(i - 1)}>Back</button>}
        {i < STEPS.length - 1
          ? <button type="button" className="btn primary big" disabled={!canNext} onClick={() => setI(i + 1)}>{i === 0 ? 'Get started' : i === 4 && !p.clearance?.hasGuidance ? 'Skip for now' : 'Next'}</button>
          : <button type="button" className="btn primary big" disabled={!canNext} onClick={finish}>Report for duty</button>}
      </div>
      {i === 3 && !canNext && <p className="muted small center">Answer every question to continue.</p>}
    </div>
  );
}
